/** Localised labels for the menu entries v4l2 reports in English. */
const MENU_LABELS: Record<Locale, Record<string, string>> = {
  en: {},
  'pt-BR': {
    'manual mode': 'Manual',
    'aperture priority mode': 'Prioridade de abertura',
    'shutter priority mode': 'Prioridade de obturador',
    'auto mode': 'Automático',
    disabled: 'Desligado',
  },
}

export function controlLabel(locale: Locale, name: string): string {
  return (
    CONTROL_LABELS[locale]?.[name] ??
    CONTROL_LABELS.en[name] ??
    name.replace(/_/g, ' ').replace(/^./, (c) => c.toUpperCase())
  )
}

export function menuLabel(locale: Locale, label: string): string {
  return MENU_LABELS[locale]?.[label.toLowerCase().trim()] ?? label
}
